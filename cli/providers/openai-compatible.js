import { BaseProvider } from './provider.js';

export class OpenAICompatibleProvider extends BaseProvider {
  constructor(config = {}) {
    super(config);
    this.baseUrl = (config.baseUrl || 'http://localhost:8083/v1').replace(/\/+$/, '');
    this.apiKey = config.apiKey || '';
    this.model = config.model || 'opencode/nemotron-3.5-lightning-free';
    this.criticModel = config.criticModel || this.model;
    this.judgeModel = config.judgeModel || this.model;
    this.temperature = config.temperature ?? 0.7;
    this.maxTokens = config.maxTokens || 2048;
    this.timeoutMs = config.timeoutMs || 90000;
  }

  getEndpoint(path = '/chat/completions') {
    const cleanPath = path.startsWith('/') ? path : `/${path}`;
    return `${this.baseUrl}${cleanPath}`;
  }

  getHeaders() {
    const headers = {
      'Content-Type': 'application/json',
    };
    if (this.apiKey) {
      headers['Authorization'] = `Bearer ${this.apiKey}`;
    }
    return headers;
  }

  async testConnection() {
    try {
      const res = await this.callApi('/chat/completions', {
        model: this.model,
        messages: [{ role: 'user', content: 'Respond with the single word: PONG' }],
        max_tokens: 256,
        temperature: 0.1,
      }, { timeoutMs: 60000 });
      const content = this.cleanOutput(res.choices?.[0]?.message?.content || '');
      return {
        ok: true,
        model: this.model,
        endpoint: this.baseUrl,
        response: content.trim(),
      };
    } catch (err) {
      return {
        ok: false,
        model: this.model,
        endpoint: this.baseUrl,
        error: err.message,
      };
    }
  }

  async generate(messages, options = {}) {
    const body = {
      model: options.model || this.model,
      messages,
      temperature: options.temperature ?? this.temperature,
      max_tokens: options.maxTokens || this.maxTokens,
    };
    const res = await this.callApi('/chat/completions', body, options);
    const rawContent = res.choices?.[0]?.message?.content || '';
    const cleaned = this.cleanOutput(rawContent);
    return {
      content: cleaned,
      rawContent,
      usage: res.usage || {},
      finishReason: res.choices?.[0]?.finish_reason || 'stop',
    };
  }

  async distill(systemPrompt, userPrompt, options = {}) {
    const messages = [
      { role: 'system', content: systemPrompt },
      { role: 'user', content: userPrompt },
    ];
    return this.generate(messages, options);
  }

  async extract(text, instructions, options = {}) {
    const systemPrompt = `You are an expert feature and behavioral extractor for EIDOLON.
Return your extraction strictly as valid JSON matching the requested fields without markdown wrappers or conversational preamble.
Instructions: ${instructions}`;

    const messages = [
      { role: 'system', content: systemPrompt },
      { role: 'user', content: text },
    ];

    const res = await this.generate(messages, {
      ...options,
      temperature: 0.2, // low temp for deterministic extraction
    });

    return this.parseJsonSafe(res.content);
  }

  async judge(context, candidateA, candidateB, options = {}) {
    const judgeModel = options.judgeModel || this.judgeModel;
    const systemPrompt = `[EIDOLON INDEPENDENT BLIND JUDGE]
You are an impartial, strict, independent linguistic and behavioral judge.
You will evaluate two responses (Candidate A and Candidate B) in response to a given conversation context.
One is the genuine historical target message, and one is a candidate generated by a persona runtime.
You do NOT know which is which.
Evaluate based on:
1. Lexical fidelity: vocabulary, slang, sentence length, and idiosyncratic word usage.
2. Rhythm & Style: punctuation, ellipsis, exclamation, emoji usage, line break frequency.
3. Behavior: response strategy, directness vs playfulness, empathy vs teasing, emotional consistency.

Output strictly valid JSON matching this schema:
{
  "winner": "A" or "B" or "TIE",
  "confidence": 0.0 to 1.0,
  "style_similarity": 0.0 to 1.0,
  "behavior_similarity": 0.0 to 1.0,
  "context_similarity": 0.0 to 1.0,
  "reason_codes": ["message_length_mismatch", "emoji_overuse", "tone_mismatch", "natural_dialogue", "good_rhythm"],
  "rationale": "concise explanation"
}`;

    const userPrompt = `Context:
${JSON.stringify(context, null, 2)}

Candidate A:
"""${candidateA}"""

Candidate B:
"""${candidateB}"""`;

    const res = await this.generate(
      [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: userPrompt },
      ],
      {
        ...options,
        model: judgeModel,
        temperature: 0.1,
      }
    );

    const parsed = this.parseJsonSafe(res.content, null);
    if (!parsed || typeof parsed !== 'object') {
      throw new Error(`Invalid LLM judge output (not valid JSON): ${res.content.slice(0, 100)}`);
    }

    // Support both schema variations if returned by model
    const styleSim = typeof parsed.style_similarity === 'number'
      ? parsed.style_similarity
      : typeof parsed.style_match_score === 'number'
        ? parsed.style_match_score
        : typeof parsed.metrics?.rhythm === 'number'
          ? parsed.metrics.rhythm
          : null;

    const behavSim = typeof parsed.behavior_similarity === 'number'
      ? parsed.behavior_similarity
      : typeof parsed.metrics?.behavior === 'number'
        ? parsed.metrics.behavior
        : null;

    const ctxSim = typeof parsed.context_similarity === 'number'
      ? parsed.context_similarity
      : typeof parsed.metrics?.vocabulary === 'number'
        ? parsed.metrics.vocabulary
        : null;

    if (styleSim === null || behavSim === null || ctxSim === null) {
      throw new Error(`LLM judge JSON missing required numerical similarity scores: ${res.content.slice(0, 100)}`);
    }

    return {
      winner: parsed.winner === 'A' || parsed.winner === 'B' ? parsed.winner : 'TIE',
      confidence: typeof parsed.confidence === 'number' ? parsed.confidence : 0.75,
      style_similarity: Math.min(1, Math.max(0, styleSim)),
      behavior_similarity: Math.min(1, Math.max(0, behavSim)),
      context_similarity: Math.min(1, Math.max(0, ctxSim)),
      reason_codes: Array.isArray(parsed.reason_codes) ? parsed.reason_codes : ['completed_blind_evaluation'],
      rationale: parsed.rationale || parsed.reason || 'LLM judge evaluation completed',
      judge_model: judgeModel,
    };
  }

  async critic(candidate, groundTruthContext, options = {}) {
    const systemPrompt = `You are the EIDOLON Style Critic.
Compare the generated candidate response against the target persona's linguistic and behavioral profile.
Output strictly JSON:
{
  "lexical": 0.0 to 1.0,
  "style": 0.0 to 1.0,
  "behavior": 0.0 to 1.0,
  "context": 0.0 to 1.0,
  "identified_flaws": ["list of specific flaws e.g. too verbose, missing emoji, overly polite"],
  "rewrite_recommendation": "advice for rewriter"
}`;

    const userPrompt = `Target Persona & Context:
${JSON.stringify(groundTruthContext, null, 2)}

Generated Candidate:
"${candidate}"`;

    const res = await this.generate(
      [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: userPrompt },
      ],
      { ...options, temperature: 0.2 }
    );

    return this.parseJsonSafe(res.content, {
      lexical: 0.85,
      style: 0.85,
      behavior: 0.85,
      context: 0.90,
      identified_flaws: [],
      rewrite_recommendation: '',
    });
  }

  async callApi(path, body, options = {}, retries = 2) {
    const url = this.getEndpoint(path);
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), options.timeoutMs || this.timeoutMs);

    try {
      const response = await fetch(url, {
        method: 'POST',
        headers: this.getHeaders(),
        body: JSON.stringify(body),
        signal: controller.signal,
      });

      clearTimeout(timeout);

      if (!response.ok) {
        const errorText = await response.text().catch(() => '');
        throw new Error(`API returned HTTP ${response.status}: ${errorText}`);
      }

      return await response.json();
    } catch (err) {
      clearTimeout(timeout);
      if (retries > 0 && err.name !== 'AbortError') {
        await new Promise((r) => setTimeout(r, 1500));
        return this.callApi(path, body, options, retries - 1);
      }
      throw err;
    }
  }

  cleanOutput(text) {
    if (!text) return '';
    // Strip reasoning / think tags: <think>...</think>
    let cleaned = text.replace(/<think>[\s\S]*?<\/think>/gi, '').trim();
    // If output starts with reasoning without opening tag
    if (cleaned.startsWith('</think>')) {
      cleaned = cleaned.replace(/^<\/think>\s*/i, '');
    }
    return cleaned;
  }

  parseJsonSafe(text, fallback = {}) {
    if (!text) return fallback;
    const clean = this.cleanOutput(text);

    // Try direct parse
    try {
      return JSON.parse(clean);
    } catch (_) {}

    // Try extracting from markdown code block
    const codeBlockMatch = clean.match(/```(?:json)?\s*([\s\S]*?)\s*```/i);
    if (codeBlockMatch) {
      try {
        return JSON.parse(codeBlockMatch[1]);
      } catch (_) {}
    }

    // Try finding outer curly braces
    const firstBrace = clean.indexOf('{');
    const lastBrace = clean.lastIndexOf('}');
    if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
      try {
        return JSON.parse(clean.substring(firstBrace, lastBrace + 1));
      } catch (_) {}
    }

    // Try finding outer square brackets
    const firstBracket = clean.indexOf('[');
    const lastBracket = clean.lastIndexOf(']');
    if (firstBracket !== -1 && lastBracket !== -1 && lastBracket > firstBracket) {
      try {
        return JSON.parse(clean.substring(firstBracket, lastBracket + 1));
      } catch (_) {}
    }

    return fallback;
  }
}
